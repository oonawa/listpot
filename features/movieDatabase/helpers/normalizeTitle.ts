/**
 * TMDB 検索クエリ用にタイトルを正規化する。
 *
 * 配信サービスのタイトルには TMDB に存在しない版表記（「（字幕版）」「（字幕／吹替）」など）や
 * 商標記号が含まれ、そのまま検索すると 0 件になる。表示用タイトルは元の文字列を保持し、
 * 検索クエリを組み立てる直前にこのヘルパーを通す。
 */

/**
 * 版表記の括弧。括弧内に「字幕」「吹替」「吹き替え」のいずれかを含むものだけを対象にする。
 * 先読みで括弧内を判定してから本体を消費することで、
 * 「（1954）」のような版表記でない括弧は残す。
 */
const EDITION_ANNOTATION = /[（(](?=[^（()）]*(?:字幕|吹替|吹き替え))[^（()）]*[）)]/g;

export function normalizeTitle(title: string): string {
	return (
		title
			.replace(/･/g, "・")
			// 括弧を全角に寄せてから版表記を判定する
			.replace(/\(/g, "（")
			.replace(/\)/g, "）")
			.replace(/\s+/g, " ")
			.replace(EDITION_ANNOTATION, "")
			.replace(/™/g, "")
			// 版表記の除去で括弧の前後に空白が残るため、もう一度畳み込む
			.replace(/\s+/g, " ")
			.trim()
	);
}
